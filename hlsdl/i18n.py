def tr(lang: str, key: str, **kw) -> str:
    """Traduz uma chave do backend, com fallback para PT e para a própria chave."""
    catalog = BACKEND.get(lang) or BACKEND[DEFAULT_LANG]
    msg = catalog.get(key) or BACKEND[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            msg = msg.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass
    return msg


def translator(lang: str) -> Callable[..., str]:
    """Devolve uma função ``key -> mensagem`` já fixada no idioma."""

    def _t(key: str, **kw) -> str:
        return tr(lang, key, **kw)

    return _t
